"""Карусель №28 «Как проверить банку за 30 секунд» (6 слайдов, 1080×1350).

Лайфхак-система (`lifehack_layout`). Акцент — глубокая мята #0E9E78: пост про
всю линейку, а не про один товар.

Не путать с постом №13 «5 строк на этикетке»: там про то, честный ли состав,
здесь — настоящая ли банка.

Сцены сняты В МАГАЗИНЕ, а не дома: проверяют банку именно там, плюс лента
перестаёт быть сплошной квартирой. Код маркировки НЕ генерируем — нейросеть
нарисует нерабочий квадратик, а показывать фальшивый код в посте про подделки
нельзя. Вместо кода — действие: руки поворачивают банку торцом.

⚠️ Формулировки про приложение «Честный знак» намеренно осторожные: пишем, что
оно показывает сведения о товаре и статус кода, без перечисления полей — состав
экрана меняется от версии к версии.
"""
import os

from ig_automation.brand_overlay import _hex
from ig_automation.lifehack_layout import cover, step, bullets

SRC = "/private/tmp/claude-501/-Users-maksimrogoznikov-projects/f76aea07-d110-4ec0-ae31-6649558b262e/scratchpad/p28"
OUT = "output/Карусели/post28_проверка"
ACC = _hex("#0E9E78")
os.makedirs(OUT, exist_ok=True)
T = 6

cover(f"{OUT}/01.png", f"{SRC}/cover3.png",
      ["Как проверить", "банку"], "четыре шага за 30 секунд", ACC, total=T)

step(f"{OUT}/02.png", 2, None, "Найти код маркировки",
     "Поверни упаковку боком: код «Честного знака» — это квадратик из мелких точек, "
     "а не полосатый штрихкод. Он уникален для конкретной банки, а не для всей "
     "партии: две одинаковые упаковки имеют разные коды.",
     ACC, photo=f"{SRC}/code2.png", total=T)

step(f"{OUT}/03.png", 3, None, "Отсканировать в приложении",
     "Бесплатное приложение «Честный знак» покажет сведения о товаре и статус кода. "
     "Код не читается, не находится в системе или числится выведенным из оборота — "
     "это повод не покупать.",
     ACC, photo=f"{SRC}/phone3.png", total=T)

bullets(f"{OUT}/04.png", 4, "Проверить СГР",
        ["На упаковке БАД должен быть номер свидетельства о госрегистрации",
         "Он проверяется в открытом реестре Роспотребнадзора",
         "Номера на банке нет вообще — это уже вопрос к продавцу"],
        ACC, note="СГР подтверждает, что состав прошёл проверку перед выходом на рынок.",
        total=T)

step(f"{OUT}/05.png", 5, None, "Срок и упаковка",
     "Дата и номер партии должны быть нанесены на упаковку, а не наклеены поверх "
     "старой маркировки. Защитная мембрана под крышкой — целая, без надрывов.",
     ACC, photo=f"{SRC}/seal3.png", total=T)

bullets(f"{OUT}/06.png", 6, "Итого четыре шага",
        ["Найти квадратный код маркировки на упаковке",
         "Отсканировать приложением «Честный знак»",
         "Сверить номер СГР в реестре",
         "Посмотреть на срок годности и мембрану"],
        ACC, note="У нас всё это есть на каждой банке — проверяйте, это нормально.",
        total=T)

print("готово →", OUT)
